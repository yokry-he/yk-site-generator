import { Hono } from 'hono'
import { cors } from 'hono/cors'
import { logger } from 'hono/logger'
import { HTTPException } from 'hono/http-exception'
import { env } from './env'
import { requestTelemetryMiddleware } from './lib/observability'
import { errorBody } from './types'
import health from './routes/health'
import generate from './routes/generate'
import providers from './routes/providers'
import shares from './routes/shares'
import sharePage from './routes/share-page'
import auth from './routes/auth'
import projects from './routes/projects'
import engineeringProjects from './routes/engineering-projects'
import quota from './routes/quota'
import publications from './routes/publications'
import brandKits from './routes/brand-kits'
import brandAssets from './routes/brand-assets'
import templates from './routes/templates'
import features from './routes/features'
import onboarding from './routes/onboarding'
import feedback from './routes/feedback'
import adminStorageHealth from './routes/admin-storage-health'
import adminOperations from './routes/admin-operations'
import admin from './routes/admin'
import sitePage,{serveSiteFromHost} from './routes/site-page'
export function createApp(){const app=new Hono();app.use('*',requestTelemetryMiddleware);app.use('*',logger());app.use('/api/*',cors({origin:env.corsOrigins,credentials:true,allowMethods:['GET','POST','PUT','PATCH','DELETE','OPTIONS'],allowHeaders:['Content-Type','Authorization','X-Share-Delete-Token','X-Request-ID','X-Anonymous-ID'],exposeHeaders:['Content-Length','X-Request-ID'],maxAge:600}));app.route('/api/health',health);app.route('/api/generate',generate);app.route('/api/providers',providers);app.route('/api/shares',shares);app.route('/api/auth',auth);app.route('/api/projects',projects);app.route('/api/engineering-projects',engineeringProjects);app.route('/api/quota',quota);app.route('/api/publications',publications);app.route('/api/brand-kits',brandKits);app.route('/api/brand-assets',brandAssets);app.route('/api/templates',templates);app.route('/api/features',features);app.route('/api/onboarding',onboarding);app.route('/api/feedback',feedback);app.route('/api/admin/health',adminStorageHealth);app.route('/api/admin',adminOperations);app.route('/api/admin',admin);app.route('/s',sharePage);app.route('/site',sitePage);app.get('*',async(c,next)=>{const response=await serveSiteFromHost(c);if(response)return response;await next()});app.notFound((c)=>c.json(errorBody('NOT_FOUND',`路径不存在:${c.req.method} ${c.req.path}`),404));app.onError((err,c)=>{if(err instanceof HTTPException)return c.json(errorBody(`HTTP_${err.status}`,err.message),err.status);console.error('[server] 未捕获异常:',err);return c.json(errorBody('INTERNAL_ERROR','服务器内部错误'),500)});return app}
